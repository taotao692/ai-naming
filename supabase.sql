-- Supabase 建表 SQL（控制台 → SQL Editor → 整段粘贴执行）
-- 表结构按老师给的参考 SQL：name_history

create table if not exists public.name_history (
  id               bigint generated by default as identity primary key,
  user_requirement text        not null,   -- 用户起名需求
  name_result      text        not null,   -- 三组名字与寓意
  model_name       text        not null,   -- 使用的模型，形如 doubao:ep-xxx
  created_at       timestamptz not null default now()
);

-- 按时间倒序翻记录用
create index if not exists name_history_created_at_idx
  on public.name_history (created_at desc);


